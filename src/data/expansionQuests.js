import { getOfficialBlueprint } from './officialBlueprints.js';

// Adaptador inteligente de planos oficiales para expansiones:
// Conserva 100% la arquitectura verificada (paredes, puertas, darkCells, mobiliario)
// y transforma el elenco de enemigos al tema oficial de cada expansión.
function adaptBlueprintForExpansion(bpNum, monsterMap = {}, extraNotes = {}) {
  const bp = getOfficialBlueprint(bpNum);
  const items = bp.items.map((it) => {
    const mappedType = monsterMap[it.type] || it.type;
    const note = extraNotes[`${it.x},${it.y}`] || it.note;
    return { ...it, type: mappedType, ...(note ? { note } : {}) };
  });
  return {
    startRoom: bp.startRoom,
    darkCells: bp.darkCells,
    items,
  };
}

